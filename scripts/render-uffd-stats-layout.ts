import { readFileSync, writeFileSync } from 'node:fs';
import * as z from 'zod';

export const STATS_LAYOUT_FILE = 'host/uffd-handler/stats-layout.json';
export const GO_LAYOUT_FILE = 'host/uffd-handler/stats_layout.go';
export const TS_LAYOUT_FILE = 'packages/daemon/src/vm/vmm/uffd-stats-layout.ts';

// each field is a little-endian uint64, at its index times 8
const FIELD_BYTES = 8;

const FieldSchema = z.object({
  name: z.string().regex(/^[a-z][A-Za-z]*$/u),
  description: z.string(),
});

const StatsLayoutSchema = z.object({ fields: z.array(FieldSchema).min(1) });

export type StatsLayout = z.infer<typeof StatsLayoutSchema>;

export function parseStatsLayout(text: string): StatsLayout {
  return StatsLayoutSchema.parse(JSON.parse(text));
}

export function renderGoLayout(layout: Readonly<StatsLayout>): string {
  const fields = layout.fields.flatMap((field, index) => [
    `// ${field.description}`,
    `const stats${field.name.charAt(0).toUpperCase()}${field.name.slice(1)} = ${String(index)}`,
    '',
  ]);

  return [
    `// Code generated by bun run gen:uffd-stats from stats-layout.json. DO NOT EDIT.`,
    '',
    'package main',
    '',
    `// The stats file holds one little-endian uint64 per field, at its index times ${String(FIELD_BYTES)}.`,
    '',
    ...fields,
    `const statsFields = ${String(layout.fields.length)}`,
    '',
  ].join('\n');
}

export function renderTsLayout(layout: Readonly<StatsLayout>): string {
  const offsets = layout.fields.map(
    (field, index) => `  ${field.name}: ${String(index * FIELD_BYTES)},`,
  );

  return [
    `// Generated by bun run gen:uffd-stats from ${STATS_LAYOUT_FILE}. Edit the schema, not this file.`,
    '',
    '// the byte offset of each little-endian uint64 in the page handler stats file',
    'export const UFFD_STATS_OFFSETS = {',
    ...offsets,
    '} as const;',
    '',
    `export const UFFD_STATS_BYTES = ${String(layout.fields.length * FIELD_BYTES)};`,
    '',
  ].join('\n');
}

function main(): void {
  const layout = parseStatsLayout(readFileSync(STATS_LAYOUT_FILE, 'utf8'));

  writeFileSync(GO_LAYOUT_FILE, renderGoLayout(layout));
  writeFileSync(TS_LAYOUT_FILE, renderTsLayout(layout));

  console.log(`render-uffd-stats-layout: wrote ${GO_LAYOUT_FILE} and ${TS_LAYOUT_FILE}`);
}

if (import.meta.main) {
  main();
}
