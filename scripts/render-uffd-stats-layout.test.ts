import { expect, onTestFinished, test } from 'bun:test';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { $ } from 'bun';
import {
  GO_LAYOUT_FILE,
  STATS_LAYOUT_FILE,
  TS_LAYOUT_FILE,
  parseStatsLayout,
  renderGoLayout,
  renderTsLayout,
} from './render-uffd-stats-layout';

function setupTest() {
  const checkout = mkdtempSync(join(tmpdir(), 'imp-uffd-stats-layout-'));

  onTestFinished(() => {
    rmSync(checkout, { recursive: true, force: true });
  });

  mkdirSync(join(checkout, 'host', 'uffd-handler'), { recursive: true });
  mkdirSync(join(checkout, 'packages', 'daemon', 'src', 'vm', 'vmm'), { recursive: true });

  return { checkout, scriptPath: join(import.meta.dir, 'render-uffd-stats-layout.ts') };
}

test('it writes the Go and TypeScript layouts of the schema in the checkout it runs in', async () => {
  const ctx = setupTest();

  writeFileSync(
    join(ctx.checkout, STATS_LAYOUT_FILE),
    '{ "fields": [{ "name": "reads", "description": "the reads" }] }\n',
  );

  const result = await $`bun ${ctx.scriptPath}`.cwd(ctx.checkout).nothrow().quiet();

  expect({
    exitCode: result.exitCode,
    go: readFileSync(join(ctx.checkout, GO_LAYOUT_FILE), 'utf8'),
    ts: readFileSync(join(ctx.checkout, TS_LAYOUT_FILE), 'utf8'),
  }).toStrictEqual({
    exitCode: 0,
    go: [
      '// Code generated by bun run gen:uffd-stats from stats-layout.json. DO NOT EDIT.',
      '',
      'package main',
      '',
      '// The stats file holds one little-endian uint64 per field, at its index times 8.',
      '',
      '// the reads',
      'const statsReads = 0',
      '',
      'const statsFields = 1',
      '',
    ].join('\n'),
    ts: [
      '// Generated by bun run gen:uffd-stats from host/uffd-handler/stats-layout.json. Edit the schema, not this file.',
      '',
      '// the byte offset of each little-endian uint64 in the page handler stats file',
      'export const UFFD_STATS_OFFSETS = {',
      '  reads: 0,',
      '} as const;',
      '',
      'export const UFFD_STATS_BYTES = 8;',
      '',
    ].join('\n'),
  });
});

// a schema change without `bun run gen:uffd-stats` fails here
test('it matches the committed Go layout of the page handler stats file', () => {
  const schema = readFileSync(join(import.meta.dir, '..', STATS_LAYOUT_FILE), 'utf8');
  const committed = readFileSync(join(import.meta.dir, '..', GO_LAYOUT_FILE), 'utf8');

  expect(renderGoLayout(parseStatsLayout(schema))).toBe(committed);
});

test('it matches the committed TypeScript layout of the page handler stats file', () => {
  const schema = readFileSync(join(import.meta.dir, '..', STATS_LAYOUT_FILE), 'utf8');
  const committed = readFileSync(join(import.meta.dir, '..', TS_LAYOUT_FILE), 'utf8');

  expect(renderTsLayout(parseStatsLayout(schema))).toBe(committed);
});

test('it numbers each field of the schema in order for Go', () => {
  expect(
    renderGoLayout({
      fields: [
        { name: 'reads', description: 'the reads' },
        { name: 'waitNs', description: 'the wait' },
      ],
    }),
  ).toBe(
    [
      '// Code generated by bun run gen:uffd-stats from stats-layout.json. DO NOT EDIT.',
      '',
      'package main',
      '',
      '// The stats file holds one little-endian uint64 per field, at its index times 8.',
      '',
      '// the reads',
      'const statsReads = 0',
      '',
      '// the wait',
      'const statsWaitNs = 1',
      '',
      'const statsFields = 2',
      '',
    ].join('\n'),
  );
});

test('it gives each field of the schema its byte offset for TypeScript', () => {
  expect(
    renderTsLayout({
      fields: [
        { name: 'reads', description: 'the reads' },
        { name: 'waitNs', description: 'the wait' },
      ],
    }),
  ).toBe(
    [
      '// Generated by bun run gen:uffd-stats from host/uffd-handler/stats-layout.json. Edit the schema, not this file.',
      '',
      '// the byte offset of each little-endian uint64 in the page handler stats file',
      'export const UFFD_STATS_OFFSETS = {',
      '  reads: 0,',
      '  waitNs: 8,',
      '} as const;',
      '',
      'export const UFFD_STATS_BYTES = 16;',
      '',
    ].join('\n'),
  );
});

test('it refuses a schema field whose name is not camelCase', () => {
  expect(() =>
    parseStatsLayout('{ "fields": [{ "name": "serve_ns", "description": "the time" }] }'),
  ).toThrow();
});
